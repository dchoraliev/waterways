CREATE OR REPLACE FUNCTION public.insert_water_batch(rows jsonb)
 RETURNS bigint
 LANGUAGE plpgsql
AS $function$
declare
  new_batch_id bigint;
begin
  -- 1. create batch
  insert into water_data_batch default values
  returning id into new_batch_id;

  -- 2. insert rows
  insert into water_data (
    "Timestamp",
    "Lat",
    "Lon",
    "Satellites",
    "Air_Temp_F",
    "Humidity_Pct",
    "Pressure_inHg",
    "PM1_0",
    "PM2_5",
    "PM10_0",
    "Light_Clear_lux",
    "Light_415nm",
    "Light_555nm",
    "Light_680nm",
    "Sound_dB",
    "Water_Temp_F",
    "Water_DO_mgL",
    "Water_EC_uS",
    batch_id
  )
  select
    x."Timestamp",
    x."Lat",
    x."Lon",
    x."Satellites",
    x."Air_Temp_F",
    x."Humidity_Pct",
    x."Pressure_inHg",
    x."PM1_0",
    x."PM2_5",
    x."PM10_0",
    x."Light_Clear_lux",
    x."Light_415nm",
    x."Light_555nm",
    x."Light_680nm",
    x."Sound_dB",
    x."Water_Temp_F",
    x."Water_DO_mgL",
    x."Water_EC_uS",
    new_batch_id
  from jsonb_to_recordset(rows) as x(
    "Timestamp" timestamptz,
    "Lat" double precision,
    "Lon" double precision,
    "Satellites" double precision,
    "Air_Temp_F" double precision,
    "Humidity_Pct" double precision,
    "Pressure_inHg" double precision,
    "PM1_0" double precision,
    "PM2_5" double precision,
    "PM10_0" double precision,
    "Light_Clear_lux" double precision,
    "Light_415nm" double precision,
    "Light_555nm" double precision,
    "Light_680nm" double precision,
    "Sound_dB" double precision,
    "Water_Temp_F" double precision,
    "Water_DO_mgL" double precision,
    "Water_EC_uS" double precision
  );

  return new_batch_id;
end;
$function$
;

CREATE OR REPLACE FUNCTION public.sync_updated_observation_category_name()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
begin
  update public.observations
  set categories = array_replace(categories, old.type, new.type)
  where categories is not null
    and categories @> array[old.type];

  return new;
end;
$function$
;

CREATE OR REPLACE FUNCTION public.rls_auto_enable()
 RETURNS event_trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog'
AS $function$
DECLARE
  cmd record;
BEGIN
  FOR cmd IN
    SELECT *
    FROM pg_event_trigger_ddl_commands()
    WHERE command_tag IN ('CREATE TABLE', 'CREATE TABLE AS', 'SELECT INTO')
      AND object_type IN ('table','partitioned table')
  LOOP
     IF cmd.schema_name IS NOT NULL AND cmd.schema_name IN ('public') AND cmd.schema_name NOT IN ('pg_catalog','information_schema') AND cmd.schema_name NOT LIKE 'pg_toast%' AND cmd.schema_name NOT LIKE 'pg_temp%' THEN
      BEGIN
        EXECUTE format('alter table if exists %s enable row level security', cmd.object_identity);
        RAISE LOG 'rls_auto_enable: enabled RLS on %', cmd.object_identity;
      EXCEPTION
        WHEN OTHERS THEN
          RAISE LOG 'rls_auto_enable: failed to enable RLS on %', cmd.object_identity;
      END;
     ELSE
        RAISE LOG 'rls_auto_enable: skip % (either system schema or not in enforced list: %.)', cmd.object_identity, cmd.schema_name;
     END IF;
  END LOOP;
END;
$function$
;

